        internal static PatchHookCatalog Inspect(Assembly game)
        {
            var catalog = new PatchHookCatalog();
            foreach (var route in Routes)
            {
                string pending = route.Domain == "" ? route.Purpose :
                    route.Domain == "Local" || PatchHealth.StateOf(route.Domain) == PatchHealthState.Ok ? null :
                    "required " + route.Domain + " hooks not healthy; " + route.Purpose;
                var input = route.Input;
                catalog.InspectNames(game.GetType(input.TypeName), input.TypeName, input.Method, input.Parameters, pending);
            }
            return catalog;
        }
