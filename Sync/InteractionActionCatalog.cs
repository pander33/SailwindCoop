        internal static PatchHookCatalog Inspect(Assembly game)
        {
            var catalog = new PatchHookCatalog();
            foreach (string name in Types) catalog.InspectType(game.GetType(name), name);
            foreach (var input in Inputs)
                catalog.InspectNames(game.GetType(input.TypeName), input.TypeName, input.Method, input.Parameters);
            return catalog;
        }
